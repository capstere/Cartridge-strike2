import test from 'node:test';
import assert from 'node:assert/strict';
import {Client} from '@colyseus/sdk';
import {createLocalServer} from '../local-server.mjs';
import {BotController} from '../../src/fps/bots.mjs';
import {glassCrossing} from '../../tools/network-glass-fixture.mjs';
import {options,ready,own,send,until,delay} from './helpers.mjs';

test('solo start, equipment authority, pane rewind, late join, HE ownership and rematch',{timeout:35000},async t=>{
  const local=await createLocalServer({port:0,testMatch:{countdownSeconds:.05}});
  t.after(()=>local.close());
  const client=new Client(local.url,{headers:{Origin:local.url}});
  const {fillBots,...defaults}=options;
  const host=await ready(await client.create('private-fps',defaults));
  const r=[...local.rooms][0],g=r.sim.game,a=r.seats.get(host.sessionId).actor;
  const command=(kind,extra={})=>host.send('match',{kind,matchId:host.state.matchId,controlEpoch:own(host).controlEpoch,...extra});
  const select=(slot,serial)=>host.send('select',{slot,serial,lifeId:a.lifeId,controlEpoch:a.controlEpoch});
  assert.equal(r.clients.length,1);assert.equal(r.bots.size,9);
  assert([...r.bots.values()].every(s=>s.actor.bot instanceof BotController));
  command('loadout',{primary:'shotgun'});command('ready',{ready:true});command('start');
  await until(()=>host.state.phase==='active','solo host starts with nine bots');
  host.send('controls',{enabled:true,lifeId:a.lifeId,controlEpoch:a.controlEpoch});
  assert.equal(a.weapon,'shotgun');
  await until(()=>g.actors.some(b=>b.bot&&b.distanceWalked>.2),'server controllers move');
  const {pane,from,dir,pose}=glassCrossing(g.world);
  Object.assign(a,pose);await delay(150);
  const stamp=r.clock.elapsedTime;
  send(host,{aim:true,yaw:pose.yaw});
  await until(()=>a.aimAmount>.8,'server ADS transition');
  send(host,{aim:true,yaw:pose.yaw,fire:true,fireId:1});
  await until(()=>host.state.brokenGlass.has(pane.id),'shot breaks pane and replicates');
  assert.equal(a.inventory.primary.ammo,7);
  assert.equal(g.world.raycast(from,dir,1.5),null,'current passage is clear');
  r.lag.shots.set(a.id,stamp);
  assert(pane.parts.some(part=>part.id===r.lag.query(a,from,dir,1.5).wall?.id),'historical pane blocks');
  await delay(900);
  send(host,{fire:true,fireId:2,yaw:pose.yaw});await delay(90);
  assert.equal(a.inventory.primary.ammo,7,'held semi-auto trigger cannot repeat');
  send(host,{reloadId:1});await until(()=>a.reloadUntil>0,'start reload');
  select('pistol',1);await until(()=>own(host).weapon==='p9','team pistol');
  assert.equal(a.reloadUntil,0);assert.equal(a.inventory.primary.ammo,7);
  command('loadout',{primary:'cr4'});await delay(70);assert.equal(a.loadout,'shotgun');
  command('loadout',{primary:'sniper'});await until(()=>own(host).loadout==='sniper','pending loadout');
  assert.equal(own(host).primary,'shotgun');
  const sid=host.sessionId,epoch=a.controlEpoch,life=a.lifeId;
  Object.assign(host.reconnection,{enabled:true,minUptime:0,minDelay:80,maxDelay:200});
  r.clients.find(c=>c.sessionId===sid).ref.terminate();
  await until(()=>own(host).controlEpoch>epoch,'reconnect adopts a fresh control epoch');
  assert.equal(host.sessionId,sid);assert.equal(a.lifeId,life);assert.equal(r.bots.size,9);
  assert.equal(a.inventory.primary.ammo,7);assert.equal(a.weapon,'p9');assert.equal(a.loadout,'sniper');
  host.send('controls',{enabled:true,lifeId:life,controlEpoch:a.controlEpoch});
  select('he',2);await until(()=>own(host).weapon==='he','equip HE');await delay(260);
  a.spawnProtectedUntil=g.state.time+5;
  send(host,{fire:true,fireId:3});await until(()=>host.state.grenades.size===1,'throw replicates');
  const grenade=g.state.grenades[0];assert.equal(grenade.owner,a);assert.equal(a.spawnProtectedUntil,0);
  send(host,{fire:true,fireId:3});assert.equal(a.inventory.he,0);
  const late=await ready(await client.joinById(host.roomId,defaults));
  assert.equal(late.state.brokenGlass.has(pane.id),true);assert.equal(late.state.grenades.size,1);
  assert.equal(r.bots.size,8);assert.equal(own(late).kills,0);
  await host.leave();await until(()=>r.bots.has(a.id),'bot replaces departing owner');
  assert.equal(r.state.ownerId,late.sessionId);
  const victim=r.seats.get(late.sessionId).actor,replacement=r.bots.get(a.id).actor;
  // Force only placement and fuse for deterministic attribution to a departed actor.
  Object.assign(grenade,{x:victim.x,y:.7,z:victim.z,vx:0,vy:0,vz:0,deadline:g.state.time+.01});
  Object.assign(victim,{hp:1,spawnProtectedUntil:0});const before=g.state.score[a.team];
  await until(()=>!victim.alive,'HE kills exposed enemy');
  assert.equal(g.state.score[a.team],before+1);assert.equal(replacement.kills,0);assert.equal(a.kills,1);
  await until(()=>victim.alive,'respawn');
  r.match.deadline=r.clock.elapsedTime;
  await until(()=>late.state.phase==='results','results include bots');
  assert.equal(JSON.parse(late.state.results).players.filter(a=>a.name.startsWith('BOT ')).length,9);
  late.send('match',{kind:'rematch',matchId:late.state.matchId,controlEpoch:own(late).controlEpoch});
  await until(()=>late.state.phase==='waiting','rematch');
  assert.equal(late.state.brokenGlass.size,0);assert.equal(late.state.grenades.size,0);
  assert.equal(g.world.glass.brokenCount,0);
  await late.leave();await until(()=>!local.rooms.size,'bots do not retain room');
});
