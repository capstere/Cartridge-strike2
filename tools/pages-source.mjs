// GitHub's branch publisher runs Jekyll on the repository root. Only the
// files in the public build may survive. CI also compares its actual output.
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';

const publicPaths = new Set(['build-info.json', ...JSON.parse(readFileSync('build-info.json')).files.map(file => file.path)]);
const ancestors = new Set();
for (const file of publicPaths) {
  let parent = file;
  while (parent.includes('/')) {
    parent = parent.slice(0, parent.lastIndexOf('/'));
    ancestors.add(parent);
  }
}
const excluded = new Set();
for (const path of execFileSync('git', ['ls-files', '-z'], {encoding:'utf8'}).split('\0').filter(Boolean)) {
  if (publicPaths.has(path) || path.startsWith('.') || path.startsWith('_')) continue;
  let prefix = '';
  for (const part of path.split('/')) {
    prefix = prefix ? prefix + '/' + part : part;
    if (!ancestors.has(prefix)) { excluded.add(prefix); break; }
  }
}
const config = [
  '# Generated by node tools/pages-source.mjs --write. CI compares the built site to build-info.json.',
  'theme: null', 'plugins: []', 'markdown_ext: cs3_unused_markdown_extension',
  'readme_index:', '  enabled: false', 'optional_front_matter:', '  enabled: false',
  'titles_from_headings:', '  enabled: false', 'exclude:',
  ...[...excluded].sort().map(path => '  - ' + JSON.stringify(path)), ''
].join('\n');
if (process.argv[2] === '--write') writeFileSync('_config.yml', config);
else if (readFileSync('_config.yml', 'utf8') !== config) throw Error('Pages exclusions are stale. Run node tools/pages-source.mjs --write.');
