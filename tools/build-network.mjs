// Reproducible compatibility manifest and the official, pinned browser SDK.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {relative,sep} from 'node:path';
import '../server/register-shared.mjs';
import {collisionContract} from '../shared/multiplayer/collision-contract.mjs';
import {CONFIG} from '../src/fps/config.mjs';
import {configContract,NETWORK_MAP,PROTOCOL_VERSION} from '../shared/multiplayer/rules.mjs';
const check=process.argv.includes('--check'),root=new URL('../',import.meta.url);
const read=path=>readFile(new URL(path,root));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const graph=JSON.parse(await read('docs/multiplayer/imports.json'));
const paths=[...Object.keys(graph),'shared/multiplayer/rules.mjs','shared/multiplayer/protocol.mjs','server/network-schema.mjs','server/network-room.mjs','server/lag-compensation.mjs','server/headless.mjs','shared/multiplayer/input.mjs','src/fps/network/session.mjs','shared/multiplayer/world.mjs','shared/multiplayer/collision-contract.mjs','shared/sha256.mjs','src/fps/network/connection.mjs','server/access.mjs','server/local-server.mjs'].sort();
const sources=await Promise.all(paths.map(async path=>[path,hash(await read(path))]));
const {loadHeadlessWorld}=await import('../server/headless.mjs');
const {world}=await loadHeadlessWorld(NETWORK_MAP);
const contract={protocolVersion:PROTOCOL_VERSION,
  protocolHash:hash(JSON.stringify(sources.filter(([path])=>['shared/multiplayer/protocol.mjs','server/network-schema.mjs'].includes(path)))),mapId:NETWORK_MAP,
  collisionHash:hash(collisionContract(world)),mapHash:hash(await read(`levels/${NETWORK_MAP}.json`)),configHash:hash(JSON.stringify(configContract())),
  buildHash:hash(JSON.stringify(sources)),tickRate:1/CONFIG.fixedStep,patchMs:50};
const files={
  'shared/multiplayer/build.mjs':Buffer.from('// Generated by tools/build-network.mjs; do not hand edit.\nexport const CONTRACT = Object.freeze('+JSON.stringify(contract,null,2)+');\n'),
  'vendor/colyseus/colyseus.js':await read('server/node_modules/@colyseus/sdk/dist/colyseus.js'),
  'vendor/colyseus/LICENSE':await read('server/node_modules/@colyseus/sdk/LICENSE'),
};
// Include the exact resolved Floor 5 furniture dependencies in the existing
// runtime allowlist. The old synthetic slice never requested these GLBs.
const {LIBRARY_MAP}=await import('../furniture-editor/library/catalog.mjs');
const info=JSON.parse(await read('build-info.json'));
const runtime=new Set([...info.files.map(f=>f.path),...Object.keys(files),
  'shared/multiplayer/world.mjs','shared/multiplayer/collision-contract.mjs','shared/sha256.mjs','src/fps/network/connection.mjs']);
for(const item of world.projectScene.items){
  const url=LIBRARY_MAP.get(item.assetId)?.url;
  if(url){const path=relative(fileURLToPath(root),fileURLToPath(new URL(url,new URL('furniture-editor/',root)))).split(sep).join('/');
    if(path.startsWith('../'))throw Error('Asset outside runtime');runtime.add(path);
  }
}
for(const asset of [...world.project.assets.local,...world.project.assets.posters])if(asset.file)runtime.add(asset.file);
info.files=await Promise.all([...runtime].sort().map(async path=>{const bytes=files[path]||await read(path);return {path,bytes:bytes.length,sha256:hash(bytes)};}));
info.bytes=info.files.reduce((n,f)=>n+f.bytes,0);
files['build-info.json']=Buffer.from(JSON.stringify(info,null,2)+'\n');
for(const [path,bytes] of Object.entries(files)){
  if(check){if(!bytes.equals(await read(path)))throw Error(path+' is stale; run npm run build --prefix server');}
  else{await mkdir(new URL('.',new URL(path,root)),{recursive:true});await writeFile(new URL(path,root),bytes);}
}
console.log(JSON.stringify({status:'PASS',check,contract,sources:sources.length,sdk:'0.18.10',sdkBytes:files['vendor/colyseus/colyseus.js'].length}));
